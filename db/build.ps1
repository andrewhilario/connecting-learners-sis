# Rebuilds db/sis_full.sql (schema + sample data + views + procedures + triggers + roles)
# Usage (from project root):  powershell -File db/build.ps1
$ErrorActionPreference = "Stop"
$dir   = $PSScriptRoot
$parts = "01_schema", "02_seed", "03_views", "04_procedures", "05_triggers", "06_roles"
$header = "-- Connecting Learners SIS - COMPLETE SCRIPT (generated by db/build.ps1 - do not edit; edit the numbered files)`n`n"
$body = ($parts | ForEach-Object { Get-Content (Join-Path $dir "$_.sql") -Raw -Encoding UTF8 }) -join "`n`n"
[IO.File]::WriteAllText((Join-Path $dir "sis_full.sql"), $header + $body, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $(Join-Path $dir 'sis_full.sql')"
